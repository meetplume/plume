## Plume

- `meetplume/plume` serves Markdown files of the project as pages of the app. A vault (`Meetplume\Plume\Vault`) maps a folder to a URL prefix, with the app's middleware, session and authorization.
- Activate the `plume-development` skill when creating or configuring a vault, when writing or editing Markdown in a vault's folder, or when asked to document the project.
- Link pages to each other with relative `.md` paths, as on GitHub, and keep images next to the page that shows them.
